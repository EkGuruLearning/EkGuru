/* =========================================================
   EkGuru — GLOBAL CONTENT GRAPH QUERY ENGINE  (Phase 7C §9)
   ---------------------------------------------------------
   A tiny, dependency-free query layer over the normalized
   content graph (data/content-graph.json — the single source of
   truth, generated by tools/build-phase7c-content-graph.py from
   real site content).

   NO data lives here: this file fetches the JSON once and indexes
   it in memory. If the fetch fails, every query returns an empty
   result set and `ready` stays a rejected promise — consumers must
   keep rendering core content regardless (API/data failure must
   never blank a page).

   API (window.EkGuruContent):
     ready()            -> Promise resolved once loaded
     all()              -> every entity
     get(id)            -> one entity or null
     byType(type)       -> entities of a type
     byLanguage(iso)    -> entities for a target language (default all)
     byLevel(level)     -> beginner|elementary|intermediate|advanced
     byTopic(topic)     -> entities tagged with a topic
     byGoal(goal)       -> entities whose topic maps to a learner goal
     byCountry(cca2)    -> entities with a country association (data-driven)
     stats()            -> per-type + per-language counts
   ========================================================= */
(function (root) {
  "use strict";

  var cache = null;
  var readyPromise = null;

  /* Resolve data/content-graph.json RELATIVE TO THIS SCRIPT, so the loader
     works from any page depth (/, /languages/, /toolbox/...). */
  function dataUrl() {
    try {
      var cs = document.currentScript;
      if (cs && cs.src) {
        var p = cs.src.split("?")[0];
        var base = p.substring(0, p.lastIndexOf("/") + 1); // .../js/
        return base + "../data/content-graph.json";
      }
    } catch (e) {}
    return "data/content-graph.json";
  }
  var DATA_URL = dataUrl();
  var GOAL_TOPICS = {
    travel: ["travel", "survival", "food", "directions"],
    family: ["family", "feelings", "courtesy"],
    speaking: ["greetings", "introductions", "courtesy", "daily-life"],
    reading: ["script", "reading", "alphabet"],
    grammar: ["grammar", "register"],
    everyday: ["daily-life", "vocabulary", "numbers", "time"],
    heritage: ["culture", "family"],
    work: ["work"],
    study: ["grammar", "vocabulary"]
  };

  function load() {
    if (readyPromise) return readyPromise;
    readyPromise = new Promise(function (resolve, reject) {
      if (typeof root.fetch !== "function") { reject(new Error("no fetch")); return; }
      root.fetch(DATA_URL, { cache: "no-cache" })
        .then(function (r) { return r.ok ? r.json() : Promise.reject(new Error("graph " + r.status)); })
        .then(function (g) {
          cache = (g && g.entities) ? g.entities : [];
          resolve(cache);
        })
        .catch(reject);
    });
    return readyPromise;
  }

  function all() { return cache || []; }

  function get(id) {
    var c = cache || [];
    for (var i = 0; i < c.length; i++) if (c[i].id === id) return c[i];
    return null;
  }

  function byType(t) { return (cache || []).filter(function (e) { return e.type === t; }); }
  function byLanguage(iso) { return (cache || []).filter(function (e) { return e.target_language === iso; }); }
  function byLevel(lvl) { return (cache || []).filter(function (e) { return e.level === lvl; }); }
  function byTopic(t) { return (cache || []).filter(function (e) { return e.topic === t; }); }
  function byGoal(goal) {
    var topics = GOAL_TOPICS[goal] || [];
    if (!topics.length) return [];
    return (cache || []).filter(function (e) { return topics.indexOf(e.topic) !== -1; });
  }
  function byCountry(cca2) {
    return (cache || []).filter(function (e) { return e.country === cca2; });
  }
  function stats() {
    var out = { total: (cache || []).length, byType: {}, byLanguage: {}, byLevel: {} };
    (cache || []).forEach(function (e) {
      out.byType[e.type] = (out.byType[e.type] || 0) + 1;
      out.byLanguage[e.target_language] = (out.byLanguage[e.target_language] || 0) + 1;
      out.byLevel[e.level] = (out.byLevel[e.level] || 0) + 1;
    });
    return out;
  }

  root.EkGuruContent = {
    ready: load, all: all, get: get,
    byType: byType, byLanguage: byLanguage, byLevel: byLevel,
    byTopic: byTopic, byGoal: byGoal, byCountry: byCountry, stats: stats,
    GOAL_TOPICS: GOAL_TOPICS
  };
})(typeof window !== "undefined" ? window : globalThis);

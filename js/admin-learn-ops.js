  function joinQA(rows) {
    // QA json: {tools:[{url, verdict, overflow:{1280,390}, steps:[{step,ok}]}]}
    var byPath = {};
    (QA && QA.tools || []).forEach(function (t) {
      var path = t.url.replace(/^https?:\/\/[^/]+/, "").replace(/\/+$/, "") + "/";
      byPath[path] = t;
    });
    return rows.map(function (r) {
      var t = byPath[r.path];
      return {
        row: r,
        verdict: t ? t.verdict : null,
        overflow: t ? t.overflow : null,
        steps: t ? t.steps : []
      };
    });
  }


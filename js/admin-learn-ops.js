  function renderEditor() {
    $("#lo-editor").innerHTML =
      '<div class="card"><h2>Content editor (export model)</h2><p class="muted">The site is static: this dashboard cannot write files. Edit fields here, then <b>Export JSON</b> to download a patch and apply it to <code>js/practice-bank.js</code> / <code>js/learning-paths.js</code>, or hand it to the person who commits.</p>' +
      '<p style="margin:8px 0"><label class="muted" style="margin-right:10px">Bank:</label><select id="lo-edit-bank"></select> ' +
      '<label class="muted" style="margin-left:14px;margin-right:10px">Item:</label><select id="lo-edit-item"></select></p>' +
      '<div id="lo-edit-fields" style="margin:10px 0"></div>' +
      '<button type="button" id="lo-edit-export" class="btn btn-primary" style="margin-right:8px">Export JSON</button>' +
      '<button type="button" id="lo-edit-copy" class="btn btn-ghost">Copy JSON</button>' +
      '<pre id="lo-edit-out" class="scroller" style="max-height:200px;overflow:auto;margin-top:10px;font-size:.78rem"></pre></div>';

    var bankSel = $("#lo-edit-bank"), itemSel = $("#lo-edit-item");
    var banks = Object.keys(BANK);
    banks.forEach(function (b) {
      var o = document.createElement("option"); o.value = b; o.textContent = b + " (" + BANK[b].length + ")"; bankSel.appendChild(o);
    });
    function fillItems() {
      itemSel.innerHTML = "";
      (BANK[bankSel.value] || []).forEach(function (it, i) {
        var o = document.createElement("option"); o.value = i; o.textContent = (i + 1) + ". " + it.q; itemSel.appendChild(o);
      });
      drawFields();
    }
    function drawFields() {
      var it = BANK[bankSel.value] && BANK[bankSel.value][itemSel.value];
      if (!it) { $("#lo-edit-fields").innerHTML = ""; return; }
      var html = '<p class="muted" style="font-size:.8rem">editing: ' + esc(bankSel.value) + "[" + esc(itemSel.value) + "]</p>";
      ["q", "a", "explain"].forEach(function (k) {
        if (it[k] == null) return;
        html += '<label style="display:block;margin:6px 0"><span class="muted" style="font-size:.8rem">' + k + '</span><br>' +
          '<input data-f="' + k + '" value="' + esc(it[k]) + '" style="width:100%"></label>';
      });
      if (Array.isArray(it.opts)) {
        html += '<label style="display:block;margin:6px 0"><span class="muted" style="font-size:.8rem">opts (one per line)</span><br>' +
          '<textarea data-f="opts" rows="4" style="width:100%">' + esc(it.opts.join("\n")) + "</textarea></label>";
      }
      if (Array.isArray(it.words)) {
        html += '<label style="display:block;margin:6px 0"><span class="muted" style="font-size:.8rem">words</span><br>' +
          '<textarea data-f="words" rows="2" style="width:100%">' + esc(it.words.join("\n")) + "</textarea></label>";
      }
      if (it.answer) {
        html += '<label style="display:block;margin:6px 0"><span class="muted" style="font-size:.8rem">answer</span><br>' +
          '<input data-f="answer" value="' + esc(Array.isArray(it.answer) ? it.answer.join(" ") : it.answer) + '" style="width:100%"></label>';
      }
      $("#lo-edit-fields").innerHTML = html;
    }
    bankSel.addEventListener("change", fillItems);
    itemSel.addEventListener("change", drawFields);
    fillItems();

    function patch() {
      var it = BANK[bankSel.value] && BANK[bankSel.value][itemSel.value];
      var out = { bank: bankSel.value, index: Number(itemSel.value), changes: {} };
      document.querySelectorAll("#lo-edit-fields [data-f]").forEach(function (el) {
        var f = el.getAttribute("data-f");
        if (f === "opts" || f === "words") out.changes[f] = el.value.split("\n").filter(function (s) { return s.trim() !== ""; });
        else out.changes[f] = el.value;
      });
      return JSON.stringify(out, null, 2);
    }
    $("#lo-edit-export").addEventListener("click", function () {
      var blob = new Blob([patch()], { type: "application/json" });
      var a = document.createElement("a");
      a.href = URL.createObjectURL(blob);
      a.download = "ekguru-practice-patch.json";
      a.click();
    });
    $("#lo-edit-copy").addEventListener("click", function () {
      $("#lo-edit-out").textContent = patch();
      navigator.clipboard && navigator.clipboard.writeText(patch());
      if (window.EkGuruToast) window.EkGuruToast.ok("Patch copied / shown below");
    });
  }


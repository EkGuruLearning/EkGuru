  /* ---------------- render: gap engine ---------------- */

  function norm(s) {
    return String(s || "").toLowerCase().replace(/[^a-z0-9\u0900-\u097f]+/g, " ").trim();
  }

  function renderGap() {
    $("#lo-gap").innerHTML =
      '<div class="card"><h2>Content gap engine</h2><p class="muted">Type a learner query. The engine checks, in order: does an existing page answer it? does an existing tool serve it? what quality is that coverage? Then it suggests ONE action. It is a decision aid — it never creates pages itself.</p>' +
      '<div class="row" style="gap:8px;margin:10px 0"><input type="search" id="lo-gap-q" placeholder="e.g. how do I say the time in Hindi?" style="flex:1">' +
      '<button type="button" id="lo-gap-run">Analyse</button></div><div id="lo-gap-out"></div></div>';
    function run() {
      var q = norm($("#lo-gap-q").value);
      if (!q) { $("#lo-gap-out").innerHTML = '<p class="muted">Enter a query first.</p>'; return; }
      var tokens = q.split(" ").filter(function (t) { return t.length > 2; });
      // IDF-style weighting: a term in every slug (like "hindi") is less
      // distinctive than a rare one (like "time"), so rare terms rank higher.
      var slugTokens = {};
      (QUALITY.pages || []).forEach(function (p) {
        var seen = {};
        norm(p.url || "").split(" ").forEach(function (t) { seen[t] = 1; });
        Object.keys(seen).forEach(function (t) { slugTokens[t] = (slugTokens[t] || 0) + 1; });
      });
      var total = Math.max(1, (QUALITY.pages || []).length);
      var weight = function (t) { return 1 + Math.log(total / (1 + (slugTokens[t] || 0))); };

      var pageHits = (QUALITY.pages || []).map(function (p) {
        var url = norm(p.url || "");
        var hay = norm((p.h1 || "") + " " + (p.title || "") + " " + (p.meta_description || ""));
        var s = 0;
        tokens.forEach(function (t) {
          if (url.indexOf(t) !== -1) s += 2 * weight(t);       // slug match counts most
          else if (hay.indexOf(t) !== -1) s += weight(t);      // heading/description match
        });
        return { p: p, s: Math.round(s * 10) / 10 };
      }).sort(function (a, b) { return (b.s - a.s) || (b.p.score - a.p.score); }).slice(0, 5);

      var toolHits = REGISTRY.map(function (r) {
        var hay = norm(r.name + " " + r.category + " " + r.path);
        var s = 0;
        tokens.forEach(function (t) { if (hay.indexOf(t) !== -1) s++; });
        return { r: r, s: s };
      }).sort(function (a, b) { return b.s - a.s; }).slice(0, 3);

      var bankHits = [];
      Object.keys(BANK).forEach(function (b) {
        (BANK[b] || []).forEach(function (it) {
          var hay = norm((it.q || "") + " " + (it.a || ""));
          var s = 0;
          tokens.forEach(function (t) { if (hay.indexOf(t) !== -1) s++; });
          if (s) bankHits.push({ bank: b, item: it, s: s });
        });
      });
      bankHits.sort(function (a, b) { return b.s - a.s; });

      var best = pageHits[0];
      var bestTool = toolHits[0];
      var matched = tokens.filter(function (t) {
        return (best && (norm((best.p.url || "") + " " + (best.p.h1 || "") + " " + (best.p.title || "")).indexOf(t) !== -1)) ||
               (bestTool && norm(bestTool.r.name).indexOf(t) !== -1);
      });

      var action, why;
      if (!best || best.s === 0) {
        action = "CREATE LESSON"; why = "no existing page mentions the query terms — the gap is real.";
      } else if (best.p.score < 65) {
        action = "IMPROVE"; why = "page " + best.p.url + " covers it but scores " + best.p.score + " (weak) — deepen the answer, add Devanagari examples and a practice link.";
      } else if (bestTool && bestTool.s > 0 && !best.p.links_tool) {
        action = "IMPROVE (add tool link)"; why = "page " + best.p.url + " is strong (" + best.p.score + ") but links no tool — link " + bestTool.r.name + ".";
      } else if (bankHits.length && !(best.p.practice_hints >= 2)) {
        action = "IMPROVE (add practice)"; why = "a practice item exists (" + bankHits[0].bank + ") but the page lacks practice hooks.";
      } else if (best.p.score >= 65 && matched.length < tokens.length) {
        action = "CREATE TOOL / CREATE PRACTICE"; why = "page covers part of the query; the uncovered terms (" + tokens.filter(function (t) { return matched.indexOf(t) === -1; }).join(", ") + ") have no page, tool or drill.";
      } else {
        action = "COVERED — no action"; why = "page " + best.p.url + " scores " + best.p.score + " and a tool/drill is already linked.";
      }

      var out = '<div style="border-left:4px solid ' + (action.indexOf("COVERED") === 0 ? "#1c7d3a" : action.indexOf("IMPROVE") === 0 ? "#b08a00" : "#c0392b") + ';padding:10px 14px;margin:12px 0;background:var(--card)">' +
        "<p><b>Suggested action:</b> " + esc(action) + "</p><p class='muted'>" + esc(why) + "</p></div>";

      out += "<p><b>Best existing pages</b></p><ul style='margin:4px 0 10px 18px'>";
      pageHits.forEach(function (h) {
        out += '<li style="font-size:.86rem"><a href="' + esc(h.p.url) + '" target="_blank" rel="noopener">' + esc(h.p.url) + "</a> · score " + h.p.score + " · " + esc(h.p.grade) + " · relevance " + h.s + "</li>";
      });
      out += "</ul>";
      out += "<p><b>Tools</b></p><ul style='margin:4px 0 10px 18px'>";
      toolHits.forEach(function (h) {
        out += '<li style="font-size:.86rem"><a href="' + esc(h.r.path) + '" target="_blank" rel="noopener">' + esc(h.r.name) + "</a> · relevance " + h.s + "</li>";
      });
      out += "</ul>";
      if (bankHits.length) {
        out += "<p><b>Practice items that touch this</b></p><ul style='margin:4px 0 10px 18px'>";
        bankHits.slice(0, 5).forEach(function (h) {
          out += '<li style="font-size:.86rem">' + esc(h.bank) + ": " + esc(h.item.q) + "</li>";
        });
        out += "</ul>";
      }
      $("#lo-gap-out").innerHTML = out;
    }
    $("#lo-gap-run").addEventListener("click", run);
    $("#lo-gap-q").addEventListener("keydown", function (e) { if (e.key === "Enter") run(); });
  }


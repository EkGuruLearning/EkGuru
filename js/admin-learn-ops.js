      if (disabled[r.slug]) { state = "DISABLED"; colour = "#c0392b"; }
      else if (j.verdict === "PASS") { state = "GREEN"; colour = "#1c7d3a"; }
      else if (j.verdict) { state = "RED"; colour = "#c0392b"; }
      var ov = j.overflow ? ("1280:" + (j.overflow["1280"] === 0 ? "ok" : j.overflow["1280"]) + " / 390:" + (j.overflow["390"] === 0 ? "ok" : j.overflow["390"])) : "—";

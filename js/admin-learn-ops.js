/* =========================================================
   EkGuru — ADMIN LEARN OPS  (v100)
   ---------------------------------------------------------
   The "Learn Ops" tab on admin.html. Reads the same single
   sources of truth as the learner-facing pages:

     js/learning-paths.js   -> window.EKGURU_PATHS
     js/practice-bank.js    -> window.EKGURU_PRACTICE_BANK
     js/learn-quality.js    -> window.EKGURU_QUALITY (generated by tools/learn-tools-audit.py)
     js/tool-registry.js    -> window.EKGURU_TOOL_REGISTRY
     reports/tool-functional-qa.json (fetched, same origin)

   Honesty rules enforced here:
     - A page listed here is scored by the STATIC audit only;
       the score is an internal quality signal, never a Google
       ranking claim.
     - A tool is only shown GREEN when the real-browser QA JSON
       says PASS. "Not tested" is UNKNOWN, never green.
     - The gap engine is a decision aid. It never generates
       pages on its own; it suggests an action a human applies.
     - The disable control records a decision in this browser's
       audit log. It does NOT change the live site — the change
       is applied in the tool page and rebuilt/deployed.
   ========================================================= */

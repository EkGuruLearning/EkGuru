let language='en';
let welcomeName='';
const original=new WeakMap();
export function translate(value){return language==='hi'?(hi[value]||value):value;}
export function setWelcome(name) {
  welcomeName=name || '';
  const heading=document.querySelector('[data-welcome]');
  if (!heading) return;
  heading.textContent=welcomeName ? (language==='hi'?'स्वागत है, ':'Welcome, ')+welcomeName : translate('My learning');
  heading.lang=language;
}
export function applyLanguage(root=document.querySelector('[data-student-page]')) {
  if(!root)return;
  const walker=document.createTreeWalker(root,NodeFilter.SHOW_TEXT);
  let node; while((node=walker.nextNode())) {
    const parent=node.parentElement;
    if(!parent || parent.closest('script,style,[data-no-translate]')) continue;
    let text=original.get(node);
    if(text===undefined){text=node.nodeValue;original.set(node,text);}
    const trimmed=text.trim();
    if (!hi[trimmed]) continue;
    node.nodeValue=text.replace(trimmed,translate(trimmed));
    parent.setAttribute('lang',language==='hi'?'hi':'en');
  }
  setWelcome(welcomeName);
}
export function initialiseLanguage() {
  const select=document.querySelector('[data-student-language]');if(!select)return;
  select.addEventListener('change',()=>{
    language=select.value==='hi'?'hi':'en';applyLanguage();
    document.querySelectorAll('[data-password-toggle]').forEach(button=>{
      const input=button.parentElement.querySelector('input');
      button.setAttribute('aria-label',translate(input.type==='password'?'Show password':'Hide password'));
    });
  });
}

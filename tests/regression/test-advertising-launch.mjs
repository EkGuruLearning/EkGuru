// Static prerequisites cannot authorize serving or attest account configuration.
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
const cwd = new URL('../../', import.meta.url);
const run = (...args) => spawnSync(process.execPath, ['tools/check-advertising-launch.mjs', ...args], { cwd, encoding: 'utf8' });
const diagnostic = run('--json');
assert.equal(diagnostic.status, 0, diagnostic.stderr || diagnostic.stdout);
const report = JSON.parse(diagnostic.stdout);
assert.equal(report.status, 'BLOCKED_ACCOUNT_AND_PRODUCTION_VERIFICATION');
assert.equal(report.launch_authorized, false);
assert.ok(Object.values(report.repository_checks).every(Boolean));
assert.ok(report.outstanding_evidence.length >= 5);
assert.equal(report.recorded_account_status, 'OWNER_REPORTED_NOT_APPROVED');
assert.equal(report.recorded_consent_status, 'REVIEW_REQUIRED_ACCOUNT_CONFIGURATION');
const release = run('--check', '--json');
assert.equal(release.status, 1, 'release must fail, even though repository prerequisites pass');
assert.equal(JSON.parse(release.stdout).launch_authorized, false);
const text = run();
assert.equal(text.status, 0);
assert.match(text.stdout, /NOT enabled/);
console.log('PASS advertising diagnostic is read-only and release remains blocked');

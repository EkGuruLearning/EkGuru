# ----------------------------------------------------------------- helpers
def read(p: Path) -> str:
    return p.read_text(encoding="utf-8")


def page(target: str) -> Path:
    p = Path(target) if target.endswith(".html") else Path(target) / "index.html"
    if not p.is_file():
        raise SystemExit(f"FATAL: /learn/ would link a page that does not exist: {target}")
    return p


def head_of(target: str) -> str:
    return read(page(target)).split("</head>", 1)[0]


def title_of(target: str) -> str:
    m = re.search(r"<title>(.*?)</title>", read(page(target)), re.S)
    if not m:
        raise SystemExit(f"FATAL: no <title> in {target}")
    return re.sub(r"\s*\|\s*EkGuru\s*$", "", unescape(m.group(1))).strip()


def desc_of(target: str, n: int = 130) -> str:
    h = head_of(target)
    m = (re.search(r'<meta name="description" content="([^"]*)"', h)
         or re.search(r'<meta content="([^"]*)" name="description"', h))
    d = unescape(m.group(1)).strip() if m else ""
    d = re.split(r"\s*Free, no sign-?up\.?", d, 1)[0].strip()
    if len(d) > n:
        cut = d[:n]
        dot = cut.rfind(". ")
        d = cut[:dot + 1] if dot >= 60 else cut.rsplit(" ", 1)[0].rstrip(",;:—- ") + "…"
    return d


def is_indexable(target: str) -> bool:
    h = head_of(target)
    m = (re.search(r'<meta[^>]*name="robots"[^>]*content="([^"]*)"', h, re.I)
         or re.search(r'<meta[^>]*content="([^"]*)"[^>]*name="robots"', h, re.I))
    return not (m and "noindex" in m.group(1).lower())


def href(target: str) -> str:
    """From learn/index.html (depth 1). Children are plain relative paths
    ("hindi-alphabet-for-beginners/" — the form tools/test-journeys.mjs
    clicks); the three held guide hubs keep the "./spanish/" spelling that
    tools/test-phase3-content.py pins."""
    if target.startswith("learn/"):
        rest = target[len("learn/"):]
        rel = rest if rest.endswith(".html") else rest.rstrip("/") + "/"
        return "./" + rel if rest in GUIDE_HUBS.values() else rel
    if target.endswith(".html"):
        return "../" + target
    return "../" + target.rstrip("/") + "/"


def subdirs(d: str, indexable_only: bool = True) -> list[str]:
    base = Path(d)
    if not base.is_dir():
        return []
    out = sorted(f"{d}/{p.name}" for p in base.iterdir() if p.is_dir() and (p / "index.html").is_file())
    return [o for o in out if is_indexable(o)] if indexable_only else out


def rungs(code: str) -> list[str]:
    return [d for d in subdirs(f"languages/{code}/level") if re.search(r"/(a|b|c)\d$", d)]


def rung_label(ds: list[str]) -> str:
    codes = [d.rsplit("/", 1)[-1].upper() for d in ds]
    return "–".join([codes[0], codes[-1]]) if len(codes) > 1 else (codes[0] if codes else "")


def card(target: str, name: str, native: str, blurb: str, meta: str, links: list[tuple[str, str]] = ()) -> str:
    extra = ""
    if links:
        extra = '<span class="li-links">' + " ".join(
            f'<a href="{href(t)}">{escape(l)}</a>' for t, l in links) + "</span>"
    return (f'<a class="li-card" href="{href(target)}"><b>{escape(name)} '
            f'<span class="li-native">{escape(native)}</span></b><span>{escape(blurb)}</span>'
            f'<span class="li-meta">{escape(meta)}</span></a>' + extra)


def li(target: str, label: str | None = None) -> str:
    return f'<li><a href="{href(target)}">{escape(label or title_of(target))}</a></li>'



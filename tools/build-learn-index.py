# ----------------------------------------------------------------- injection
def set_meta(h: str, key: str, value: str, content: str) -> str:
    c = escape(content, quote=True)
    pat1 = re.compile(rf'(<meta\b[^>]*\b{key}="{re.escape(value)}"[^>]*\bcontent=")[^"]*(")', re.I)
    pat2 = re.compile(rf'(<meta\b[^>]*\bcontent=")[^"]*("[^>]*\b{key}="{re.escape(value)}")', re.I)
    if pat1.search(h):
        return pat1.sub(lambda m: m.group(1) + c + m.group(2), h, count=1)
    if pat2.search(h):
        return pat2.sub(lambda m: m.group(1) + c + m.group(2), h, count=1)
    return h


def apply_page(h: str, region: str) -> str:
    full_title = TITLE + " | EkGuru"
    h = re.sub(r"<title>.*?</title>", f"<title>{escape(full_title)}</title>", h, count=1, flags=re.S)
    h = set_meta(h, "name", "description", DESC)
    h = set_meta(h, "property", "og:title", full_title)
    h = set_meta(h, "property", "og:description", DESC)
    h = set_meta(h, "name", "twitter:title", full_title)
    h = set_meta(h, "name", "twitter:description", DESC)
    h = re.sub(r'<p class="crumb">.*?</p>', '<p class="crumb"><a href="../">EkGuru</a> › Learn</p>', h, count=1, flags=re.S)
    h = re.sub(r'<span class="kicker">.*?</span>', f'<span class="kicker">{escape(KICKER)}</span>', h, count=1, flags=re.S)
    h = re.sub(r"<h1>.*?</h1>", f"<h1>{escape(H1)}</h1>", h, count=1, flags=re.S)
    if START in h and END in h:
        pre, rest = h.split(START, 1)
        _, post = rest.split(END, 1)
        return pre + region + post
    # First run: the old page ran from its lede to the hand-written language
    # list; the region replaces everything from the end of the hero block to
    # the global-nav markers that the phase-7 generator owns.
    m_start = re.search(r'<p class="lede">.*?</p>\s*</div>\n', h, re.S)
    m_end = re.search(r'\n<script defer="" src="../js/site-config.js"></script>', h)
    if not m_start or not m_end or m_end.start() < m_start.end():
        raise SystemExit("FATAL: cannot find the content region in learn/index.html")
    # the old lede is replaced by the generated one; the hero wrapper and the
    # .lw wrapper are closed again around the region; the page scripts
    # (site-config, scroll-restore, recovery, analytics, service worker) and
    # the hand-written language list that followed them are replaced by the
    # scripts alone — the list is what this region now is.
    scripts_end = re.search(r'\n<!-- ═+ ALL LANGUAGES — UNIFIED HUB ═+ -->', h)
    nav = re.search(r'\n<!-- ekguru:global-nav:start -->', h)
    if not scripts_end or not nav or not (m_end.start() < scripts_end.start() < nav.start()):
        raise SystemExit("FATAL: learn/index.html script block / language list not where expected")
    scripts = h[m_end.start():scripts_end.start()]
    return h[:m_start.start()] + "</div>\n" + region + "\n</div>" + scripts + h[nav.start():]


def apply_pointer(h: str, up: str, what: str) -> str:
    """courses/ and languages/: one banner under the h1 pointing at /learn/."""
    banner = (f'{POINTER}\n<p class="callout" style="margin:14px 0 20px"><strong>Everything on this page now opens from one '
              f'place:</strong> <a href="{up}learn/">Learn a language — every course, one page</a>. {what}</p>')
    if POINTER in h:
        return re.sub(re.escape(POINTER) + r"\n<p [^>]*>.*?</p>", banner, h, count=1, flags=re.S)
    h2, n = re.subn(r"(<h1[^>]*>.*?</h1>)", lambda m: m.group(1) + "\n" + banner, h, count=1, flags=re.S)
    if not n:
        raise SystemExit("FATAL: no <h1> to hang the learn pointer on")
    return h2


def main() -> int:
    check = "--check" in sys.argv
    region, counts = build_region()
    jobs = [
        (PAGE, lambda h: apply_page(h, region)),
        # courses/index.html: its hero is generated by tools/build-course-hub.py,
        # which carries the same pointer itself (the course player re-renders
        # that region on load, so a banner spliced in here would vanish).
        (Path("languages/index.html"), lambda h: apply_pointer(
            h, "../", "The starter packs stay online for the links that point at them; nothing has moved or been removed.")),
    ]
    stale = []
    for path, fn in jobs:
        old = read(path)
        new = fn(old)
        if new != old:
            stale.append(str(path))
            if not check:
                path.write_text(new, encoding="utf-8")
    links = len(re.findall(r'href="', region))
    summary = (f"{counts['langs']} languages ({counts['indian']} Indian + {counts['world']} world + Hindi), "
               f"{links} links on learn/index.html")
    if check:
        if stale:
            print("STALE learn index: " + ", ".join(stale) + " — run: python3 tools/build-learn-index.py")
            return 1
        print(f"ok    learn index is current — {summary}")
        return 0
    print(f"wrote {', '.join(stale) if stale else 'nothing (already current)'} — {summary}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

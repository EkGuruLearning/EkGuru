# ----------------------------------------------------------------- helpers
def read(p: Path) -> str:
    return p.read_text(encoding="utf-8")


def page(target: str) -> Path:
    """Site-root-relative directory ('learn/paths/hindi-from-zero') or file
    ('find-tutors.html') -> the file on disk. Missing = build error."""
    p = Path(target) if target.endswith(".html") else Path(target) / "index.html"
    if not p.is_file():
        raise SystemExit(f"FATAL: hub card points at a page that does not exist: {target}")
    return p


def title_of(target: str) -> str:
    m = re.search(r"<title>(.*?)</title>", read(page(target)), re.S)
    if not m:
        raise SystemExit(f"FATAL: no <title> in {target}")
    return re.sub(r"\s*\|\s*EkGuru\s*$", "", unescape(m.group(1))).strip()


def desc_of(target: str, n: int = 120) -> str:
    h = read(page(target))
    m = (re.search(r'<meta name="description" content="([^"]*)"', h)
         or re.search(r'<meta content="([^"]*)" name="description"', h))
    d = unescape(m.group(1)).strip() if m else ""
    # the topic chapters end their description with "Free, no sign-up. <title>"
    # — a card already says the title, and the hub says "free" once.
    d = re.split(r"\s*Free, no sign-?up\.?", d, 1)[0].strip()
    if len(d) > n:
        cut = d[:n]
        dot = cut.rfind(". ")
        d = cut[:dot + 1] if dot >= 60 else cut.rsplit(" ", 1)[0].rstrip(",;:—- ") + "…"
    return d


def is_indexable(target: str) -> bool:
    h = read(page(target)).split("</head>", 1)[0]
    m = re.search(r'<meta[^>]*name="robots"[^>]*content="([^"]*)"', h, re.I) or \
        re.search(r'<meta[^>]*content="([^"]*)"[^>]*name="robots"', h, re.I)
    return not (m and "noindex" in m.group(1).lower())


DEPTH = 2  # set per page before rendering: learn/hindi/ = 2, hindi/ = 1


def href(target: str) -> str:
    """From the page being rendered to a site-root-relative target — the
    shortest relative path (learn/x from learn/hindi/ is ../x/, which is also
    the form tools/test-phase3-content.py expects on the Hindi hub)."""
    if DEPTH == 2 and target.startswith("learn/"):
        rest = target[len("learn/"):]
        if rest.startswith("hindi/"):
            rest = rest[len("hindi/"):]
            return rest if rest.endswith(".html") else rest.rstrip("/") + "/"
        return "../" + (rest if rest.endswith(".html") else rest.rstrip("/") + "/")
    up = "../" * DEPTH
    if target.endswith(".html"):
        return up + target
    return up + target.rstrip("/") + "/"


def subdirs(d: str) -> list[str]:
    base = Path(d)
    return sorted(f"{d}/{p.name}" for p in base.iterdir()
                  if p.is_dir() and (p / "index.html").is_file())


def card(target: str, label: str | None = None, blurb: str | None = None, meta: str = "") -> str:
    ttl = label or title_of(target)
    b = blurb if blurb is not None else desc_of(target)
    if b.endswith(ttl):                       # "… what you want. Everyday Hindi"
        b = b[: -len(ttl)].rstrip()
    t, b = escape(ttl), escape(b)
    m = f' <span class="hh-meta">{escape(meta)}</span>' if meta else ""
    return f'<a class="hh-card" href="{href(target)}"><b>{t}</b><span>{b}</span>{m}</a>'


def li(target: str, label: str | None = None) -> str:
    return f'<li><a href="{href(target)}">{escape(label or title_of(target))}</a></li>'



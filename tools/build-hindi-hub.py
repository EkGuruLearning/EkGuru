def set_meta(h: str, key: str, value: str, content: str) -> str:
    """Rewrite <meta key="value" content="…"> whichever attribute order the page uses."""
    c = escape(content, quote=True)
    pat1 = re.compile(rf'(<meta\b[^>]*\b{key}="{re.escape(value)}"[^>]*\bcontent=")[^"]*(")', re.I)
    pat2 = re.compile(rf'(<meta\b[^>]*\bcontent=")[^"]*("[^>]*\b{key}="{re.escape(value)}")', re.I)
    if pat1.search(h):
        return pat1.sub(lambda m: m.group(1) + c + m.group(2), h, count=1)
    if pat2.search(h):
        return pat2.sub(lambda m: m.group(1) + c + m.group(2), h, count=1)
    return h


def apply_region(h: str, region: str, *, title: str, h1: str, desc: str, crumb: str, label: str) -> str:
    full_title = title + " | EkGuru"
    h = re.sub(r"<title>.*?</title>", f"<title>{escape(full_title)}</title>", h, count=1, flags=re.S)
    h = set_meta(h, "name", "description", desc)
    h = set_meta(h, "property", "og:title", full_title)
    h = set_meta(h, "property", "og:description", desc)
    h = set_meta(h, "name", "twitter:title", full_title)
    h = set_meta(h, "name", "twitter:description", desc)
    # JSON-LD CollectionPage name/description on the topic page (first @graph node)
    h = h.replace('"name":"Every Hindi topic","description":"The complete topical map of Hindi learning on EkGuru."',
                  f'"name":{json.dumps(h1, ensure_ascii=False)},"description":{json.dumps(desc, ensure_ascii=False)}', 1)
    h = re.sub(r'"name":"(?:Every Hindi topic, mapped|Learn Hindi — everything in one place)"',
               lambda m: f'"name":{json.dumps(h1, ensure_ascii=False)}', h)
    h = h.replace(f'"description":{json.dumps(DESC, ensure_ascii=False)}', f'"description":{json.dumps(desc, ensure_ascii=False)}')
    # learn/hindi/ JSON-LD (spaced JSON from tools/build-hindi-structure.py)
    h = re.sub(r'"name": "(?:EkGuru Learn Hindi structure|Learn Hindi — everything in one place)", "description": "[^"]*"',
               lambda m: f'"name": {json.dumps(h1, ensure_ascii=False)}, "description": {json.dumps(desc, ensure_ascii=False)}',
               h, count=1)
    # breadcrumb + h1
    h = re.sub(r'<p class="crumb">.*?</p>', crumb, h, count=1, flags=re.S)
    h = re.sub(r"<h1>.*?</h1>", f"<h1>{escape(h1)}</h1>", h, count=1, flags=re.S)
    # content region
    if START in h and END in h:
        pre, rest = h.split(START, 1)
        _, post = rest.split(END, 1)
        return pre + region + post
    # first run: from the old lede to the trust footer
    m_start = re.search(r'<p class="lede">', h)
    m_end = (re.search(r'\n<!-- =+\n\s*THE TRUST FOOTER', h)
             or re.search(r'\n</div>\n<!-- ekguru:trust-footer:start -->', h))
    if not m_start or not m_end or m_end.start() < m_start.start():
        raise SystemExit(f"FATAL: cannot find the content region in {label}")
    return h[:m_start.start()] + region + "\n" + h[m_end.start():]


def apply_hub(h: str, region: str) -> str:
    h = re.sub(r"<!-- ekguru:hindi-hub-pointer -->\n<p [^>]*>.*?</p>\n?", "", h, count=1, flags=re.S)
    return apply_region(
        h, region, title=TITLE, h1=H1, desc=DESC, label="learn/hindi/index.html",
        crumb='<p class="crumb"><a href="../../">EkGuru</a> › <a href="../">Learn</a> › Hindi</p>')


MERGED_INTO = BASE + "/learn/hindi/"                 # where /hindi/ now lives
MERGE_REFRESH = ('<meta content="0; url=' + MERGED_INTO + '#hh-topics" http-equiv="refresh"/>'
                 '<!-- ekguru:merged-into-hub -->')


def merge_into_hub(h: str) -> str:
    """hindi/index.html is a duplicate of the hub: canonical + og:url name the
    hub, and a 0-second refresh takes visitors to its topics section. The
    refresh line sits right after the canonical and is replaced in place on
    every run (never duplicated)."""
    h = re.sub(r'<link\b[^>]*\brel="canonical"[^>]*>',
               f'<link href="{MERGED_INTO}" rel="canonical"/>', h, count=1)
    h = set_meta(h, "property", "og:url", MERGED_INTO)
    h = re.sub(r'<meta\b[^>]*http-equiv="refresh"[^>]*/?>\s*<!-- ekguru:merged-into-hub -->\n?', "", h, count=1)
    h = h.replace(f'<link href="{MERGED_INTO}" rel="canonical"/>',
                  f'<link href="{MERGED_INTO}" rel="canonical"/>\n{MERGE_REFRESH}', 1)
    return h


def apply_topics(h: str, region: str) -> str:
    h = merge_into_hub(h)
    return apply_region(
        h, region, title=T_TITLE, h1=T_H1, desc=T_DESC, label="hindi/index.html",
        crumb='<p class="crumb"><a href="../">EkGuru</a> › <a href="../learn/">Learn</a> › '
              '<a href="../learn/hindi/">Hindi</a> › Topics</p>')


def main() -> int:
    check = "--check" in sys.argv
    region = build_region()
    topics = build_topics_region()
    stale = []
    for path, fn in ((HUB, lambda h: apply_hub(h, region)), (TOPICS, lambda h: apply_topics(h, topics))):
        old = read(path)
        new = fn(old)
        if new != old:
            stale.append(str(path))
            if not check:
                path.write_text(new, encoding="utf-8")
    links = len(re.findall(r'href="', region))
    if check:
        if stale:
            print("STALE hindi hub: " + ", ".join(stale) + " — run: python3 tools/build-hindi-hub.py")
            return 1
        print(f"ok    hindi hub is current ({links} links on learn/hindi/index.html)")
        return 0
    print(f"wrote {', '.join(stale) if stale else 'nothing (already current)'} — {links} links on the hub")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

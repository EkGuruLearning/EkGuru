def pinyin(text):
    """Render tone-marked syllables, grouping known words and retaining punctuation."""
    keys = sorted(PINYIN_WORDS, key=len, reverse=True)
    chunks, i = [], 0
    punctuation = set("，。！？；：、（）《》“”‘’—…")
    while i < len(text):
        ch = text[i]
        if ch in punctuation:
            if chunks:
                chunks[-1] += ch
            else:
                chunks.append(ch)
            i += 1
            continue
        if ch.isspace():
            i += 1
            continue
        word = next((w for w in keys if text.startswith(w, i)), None)
        if word:
            chunks.append(PINYIN_WORDS[word])
            i += len(word)
        elif ch in PINYIN_CHARS:
            chunks.append(PINYIN_CHARS[ch])
            i += 1
        else:
            # Latin text and numerals in a target line are retained as written.
            chunks.append(ch)
            i += 1
    rendered = ""
    for chunk in chunks:
        if not rendered:
            rendered = chunk
        elif rendered[-1] in punctuation:
            rendered += chunk
        else:
            rendered += " " + chunk
    for mark in punctuation:
        rendered = rendered.replace(mark + " ", mark)
    return rendered


def _lesson(title, aim, words, grammar, examples, mistake, worksheet):
    vocab = [V(t, pinyin(t), en) for t, en in words]
    ex = [X(t, pinyin(t), en) for t, en in examples]
    dialogue = [D("老师", *examples[0][:1], pinyin(examples[0][0]), examples[0][1]),
                D("学生", examples[1][0], pinyin(examples[1][0]), examples[1][1]),
                D("老师", examples[2][0], pinyin(examples[2][0]), examples[2][1]),
                D("学生", examples[1][0], pinyin(examples[1][0]), examples[1][1])]
    tasks = [T("Translate the first model into English.", [examples[0][0]], [examples[0][1]]),
             T("Use the lesson pattern with a different detail.",
               [examples[1][0], examples[2][0]], [examples[1][1], examples[2][1]])]
    return L(title, aim, vocab, G(*grammar, ex, [mistake]), dialogue, WS(worksheet, tasks))



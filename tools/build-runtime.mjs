#!/usr/bin/env node
/* Human-readable runtime source -> bounded browser asset. Never fetches content. */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { minify } from 'terser';
const check = process.argv.includes('--check');
const budgets = { voice: 10 * 1024, 'web-vitals': 2 * 1024 };
let stale = false;
for (const name of Object.keys(budgets)) {
  if (!existsSync(`src/runtime/${name}.js`)) continue;
  const source = readFileSync(`src/runtime/${name}.js`, 'utf8');
  const hash = createHash('sha256').update(source).digest('hex').slice(0, 20);
  const result = await minify(source, { compress: true, mangle: true, format: { comments: false }, ecma: 2018 });
  const output = `/* Generated by tools/build-runtime.mjs; source src/runtime/${name}.js; sha256 ${hash} */\n${result.code}\n`;
  if (Buffer.byteLength(output) > budgets[name]) throw Error(`${name}.js exceeds its ${budgets[name]} byte budget`);
  let before = ''; try { before = readFileSync(`js/${name}.js`, 'utf8'); } catch (_) { /* first build */ }
  if (before !== output) { if (check) { stale = true; console.error(`STALE js/${name}.js`); } else writeFileSync(`js/${name}.js`, output); }
  console.log(`${name}.js: ${Buffer.byteLength(output)} bytes (${check ? 'check' : 'build'})`);
}
process.exitCode = stale ? 1 : 0;

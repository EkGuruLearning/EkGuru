#!/usr/bin/env python3
"""Generate js/names-data.js from data/names/names.json.

Why a generated JS file instead of fetching the JSON at runtime: the
curated spelling IS the answer. "Singh" falls back to ਸਿਙ without it,
and no amount of waiting fixes a visitor who screenshots the wrong
answer in the half second before the fetch lands. 104 entries are
about 8 KB — embedding them costs nothing and removes the race.

`--check` fails when the two disagree, so they cannot drift.

  python3 tools/build-names-js.py
  python3 tools/build-names-js.py --check
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "data/names/names.json"
OUT = ROOT / "js/names-data.js"


def render() -> str:
    data = json.loads(SRC.read_text(encoding="utf-8"))
    rows = []
    for n in data["names"]:
        row = {"pa": n["pa"], "hi": n["hi"]}
        if n.get("also"):
            row["also"] = n["also"]
        rows.append((n["name"], row))

    body = ",\n".join(
        '    %s: %s' % (json.dumps(name, ensure_ascii=False), json.dumps(row, ensure_ascii=False))
        for name, row in rows
    )
    return (
        "/* GENERATED by tools/build-names-js.py from data/names/names.json.\n"
        "   Do not hand-edit: run the tool. `--check` in CI fails if this\n"
        "   file and the JSON ever disagree. */\n"
        "(function (root) {\n"
        '  "use strict";\n'
        "  var NAMES = {\n" + body + "\n  };\n"
        "\n"
        "  function lookup(name) {\n"
        '    if (!name) return null;\n'
        '    var key = String(name).trim().toLowerCase();\n'
        "    for (var k in NAMES) {\n"
        "      if (k.toLowerCase() === key) return { name: k, pa: NAMES[k].pa,\n"
        "        hi: NAMES[k].hi, also: NAMES[k].also || [] };\n"
        "    }\n"
        "    return null;\n"
        "  }\n"
        "\n"
        "  root.EkGuruNames = { all: NAMES, lookup: lookup,"
        " count: Object.keys(NAMES).length };\n"
        "})(typeof window !== \"undefined\" ? window : globalThis);\n"
    )


def main() -> int:
    want = render()
    if "--check" in sys.argv:
        if not OUT.exists():
            print("MISSING " + str(OUT.relative_to(ROOT)) + " — run: python3 tools/build-names-js.py")
            return 1
        if OUT.read_text(encoding="utf-8") != want:
            print("STALE " + str(OUT.relative_to(ROOT)) + " — run: python3 tools/build-names-js.py")
            return 1
        print("ok    names data is current")
        return 0
    OUT.write_text(want, encoding="utf-8")
    n = json.loads(SRC.read_text(encoding="utf-8"))["names"]
    print("wrote %s (%d names, %d KB)" % (OUT.relative_to(ROOT), len(n), len(want) // 1024))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

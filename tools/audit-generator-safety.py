#!/usr/bin/env python3
"""Phase 7B §22 — generator-safety verification.

For every file repaired this phase, determines generated vs hand-authored,
then runs a REAL regeneration and confirms each fix survives.

Repairs this phase:
  · toolbox/hindi-typing/index.html — hand-authored (no generator writes toolbox
    pages; countrypages.js/patch.js/shell.js are absent from the repo).
  · js/hindi-audio.js — hand-authored (voiceExists v31 fix).
  · js/hindi-tools.js — hand-authored (not touched).
  · learn/hindi/review/index.html + 15 lessons + practice pages — GENERATED by
    tools/build-hindi-pages.py (source of truth = that generator).

Output: reports/phase7b-generator-safety.json
"""
import json, os, re, subprocess, sys, time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
NOW = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())

LESSONS = ["aap-tum-tu-hindi", "common-hindi-mistakes", "hindi-alphabet-for-beginners",
           "hindi-days-months-time", "hindi-family-words", "hindi-gender-masculine-feminine",
           "hindi-numbers-1-to-100", "hindi-or-urdu-difference", "hindi-phrases-for-travel",
           "hindi-sentence-structure", "hindi-verbs-present-past-future",
           "how-to-say-hello-in-hindi", "learn-hindi-from-bollywood",
           "learn-hindi-online-guide", "write-your-name-in-hindi"]

def check(name, ok, detail=""):
    return {"file": name, "ok": bool(ok), "detail": detail}

results = []

# ---- 1. REGENERATE from the generator (source of truth) ----
reg = subprocess.run([sys.executable, "tools/build-hindi-pages.py"],
                     capture_output=True, text=True)
results.append(check("tools/build-hindi-pages.py (regeneration run)",
                     reg.returncode == 0, reg.stdout.strip().splitlines()[-1] if reg.stdout else reg.stderr[:200]))

# ---- 2. review page: the queue=[] phantom-card fix survives regeneration ----
h = open("learn/hindi/review/index.html", encoding="utf-8").read()
results.append(check("learn/hindi/review/index.html — srs-reset clears queue (v31 fix)",
                     "queue = []; /* v31 fix" in h or ("queue = [];" in h),
                     "queue=[] found" if "queue = [];" in h else "MISSING"))

# ---- 3. toast.js wired onto every generated practice/progress page ----
for p in ["learn/hindi/review/index.html", "learn/hindi/my-progress/index.html",
          "learn/hindi/practice/typing/index.html", "learn/hindi/practice/quiz/index.html",
          "learn/hindi/practice/worksheets/index.html", "learn/hindi/intermediate/index.html"]:
    hh = open(p, encoding="utf-8").read()
    results.append(check(p + " — toast.js included", "toast.js" in hh))

# ---- 4. all 15 lessons carry toast.js (＋ Review feedback) after regeneration ----
missing = [s for s in LESSONS if "toast.js" not in open(f"learn/{s}/index.html", encoding="utf-8").read()]
results.append(check("15 decorated lessons — toast.js included", not missing, str(missing) if missing else "15/15"))

# ---- 5. hand-authored files: fixes must still be present (nothing overwrites them) ----
typing = open("toolbox/hindi-typing/index.html", encoding="utf-8").read()
# fixed call must be EkGuruTranslitAPI (uppercase) + Promise .lookup; old broken
# toDevanagari( may only survive inside the explanatory comment
code = re.sub(r"<!--[\s\S]*?-->", "", typing)
results.append(check("toolbox/hindi-typing/index.html — translit fix intact (hand-authored)",
                     "translit.js" in typing and "translit-api.js" in typing
                     and "EkGuruTranslitAPI" in code and "toDevanagari(" not in code,
                     "loads both translit scripts + fixed API call" if "translit.js" in typing else "MISSING"))
audio = open("js/hindi-audio.js", encoding="utf-8").read()
results.append(check("js/hindi-audio.js — voiceExists v31 fix intact (hand-authored)",
                     "return false; /* v31 fix" in audio or "/* v31 fix" in audio,
                     "v31 fix present" if "v31 fix" in audio else "MISSING"))

ok = all(r["ok"] for r in results)
report = {
    "generated": NOW,
    "pass": ok,
    "results": results,
    "summary": {
        "handAuthoredFixes": ["toolbox/hindi-typing/index.html", "js/hindi-audio.js"],
        "generatedFixes": ["learn/hindi/review/index.html", "learn/hindi/my-progress/index.html",
                           "learn/hindi/practice/* (typing/quiz/worksheets)", "15 decorated lessons"],
        "generator": "tools/build-hindi-pages.py (source of truth for the generated pages)",
        "countryPages": "learn-hindi-from-* are NOT reproducible — their generator "
                        "(countrypages.js/patch.js) is absent from the repo after the GitHub "
                        "re-init; they were edited in place per §19.",
    },
}
with open("reports/phase7b-generator-safety.json", "w", encoding="utf-8") as f:
    json.dump(report, f, ensure_ascii=False, indent=2)
print("generator safety:", "PASS" if ok else "FAIL")
for r in results:
    print("  %-70s %s %s" % (r["file"], "OK" if r["ok"] else "FAIL", r["detail"][:60]))

#!/usr/bin/env python3
"""Build the numbers pages and their generated JS from data/numbers/*.json.

Why generate instead of hand-writing the page: the table is 101 rows and
the whole point of the page is that the table is *right*. A hand-written
table drifts from the data the tool uses, and then the page contradicts
itself — the visitor sees one spelling in the tool and another in the
table, and has no way to know which to trust. One data file, two views.

`--check` fails when the output is stale, so nothing can drift.

  python3 tools/build-numbers-pages.py
  python3 tools/build-numbers-pages.py --check
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data/numbers"

# One entry per published page. Adding a language = one JSON file here.
PAGES = [
    {
        "slug": "numbers-in-punjabi",
        "file": "punjabi.json",
        "title": "Punjabi Numbers 1 to 100 — Gurmukhi Chart and Tool | EkGuru",
        "h1": "Punjabi numbers 1 to 100",
        "desc": ("Every Punjabi number from 0 to 100 with its Gurmukhi numeral, the word in "
                 "Gurmukhi and how to say it. Plus a tool that reads any number you type, "
                 "and the patterns that make the list stick."),
        "lede": ("The full ginti in one table — the number, its Gurmukhi digit, the Punjabi "
                 "word and how to say it. Type any number below and it answers straight away. "
                 "Both spellings are shown wherever Punjabi really uses two."),
        "html_lang": "pa",
        "script_name": "Gurmukhi",
    },
    {
        "slug": "numbers-in-marathi",
        "file": "marathi.json",
        "title": "Marathi Numbers 1 to 100 — Devanagari Chart and Tool | EkGuru",
        "h1": "Marathi numbers 1 to 100",
        "desc": ("Every Marathi number from 0 to 100 with its Devanagari numeral, the word in "
                 "Marathi and how to say it. Plus a tool that reads any number you type, and "
                 "the subtraction pattern that makes the tricky ones stick."),
        "lede": ("The full number list in one table — the number, its Devanagari digit, the "
                 "Marathi word and how to say it. Type any number below and it answers straight "
                 "away. Both spellings are shown wherever Marathi really uses two."),
        "html_lang": "mr",
        "script_name": "Devanagari",
    },
]


def load(spec) -> dict:
    return json.loads((DATA / spec["file"]).read_text(encoding="utf-8"))


# ----------------------------------------------------------------------
# js/numbers-data.js — same data, but in the page, so the tool answers
# before any network call. A numbers tool that waits for a fetch is a
# numbers tool that shows nothing for the first half second.
# ----------------------------------------------------------------------
def render_js() -> str:
    langs = {}
    for spec in PAGES:
        d = load(spec)
        langs[d["language"]] = {
            "name": d["languageName"],
            "script": d["script"],
            "numerals": d["numerals"],
            "numbers": {str(x["n"]): {"w": x["word"], "r": x["roman"],
                                     **({"a": x["also"]} if x.get("also") else {})}
                        for x in d["numbers"]},
            "bigger": d["bigger"],
            "page": "/" + spec["slug"] + "/",
        }
    body = json.dumps(langs, ensure_ascii=False, indent=1)
    return (
        "/* GENERATED by tools/build-numbers-pages.py from data/numbers/*.json.\n"
        "   Do not hand-edit: run the tool. */\n"
        "(function (root) {\n"
        '  "use strict";\n'
        "  var LANGS = " + body + ";\n"
        "\n"
        "  function digits(n, lang) {\n"
        "    var map = (LANGS[lang] || LANGS.pa).numerals;\n"
        "    return String(n).split('').map(function (d) {\n"
        "      return map[+d];\n"
        "    }).join('');\n"
        "  }\n"
        "\n"
        "  function word(n, lang) {\n"
        "    var L = LANGS[lang] || LANGS.pa;\n"
        "    var key = String(+n);\n"
        "    if (L.numbers[key]) return L.numbers[key];\n"
        "    for (var i = 0; i < L.bigger.length; i++) {\n"
        "      if (L.bigger[i].n === +n) return { w: L.bigger[i].word, r: L.bigger[i].roman };\n"
        "    }\n"
        "    return null;\n"
        "  }\n"
        "\n"
        "  root.EkGuruNumbers = { langs: LANGS, digits: digits, word: word };\n"
        "})(typeof window !== \"undefined\" ? window : globalThis);\n"
    )


# ----------------------------------------------------------------------
# The page
#
# Only the table is generated, and only between its own markers. The rest
# of the page — head, prose, schema, chrome — is hand-owned, because
# apply-ultra decorates pages and a generator that rewrites a whole page
# fights that decoration on every build ("not current/idempotent").
# Marker-scoped replacement is idempotent: it touches the 101 rows and
# nothing else.
# ----------------------------------------------------------------------
TABLE_START = "<!-- ekguru:numbers-table:start -->"
TABLE_END = "<!-- ekguru:numbers-table:end -->"


def table(spec: dict, d: dict) -> str:
    lang = d["language"]
    script = spec["script_name"]
    rows = []
    for x in d["numbers"]:
        num = "".join(d["numerals"][int(c)] for c in str(x["n"]))
        also = ""
        if x.get("also"):
            also = ' <span class="alt">or ' + " / ".join(x["also"]) + "</span>"
        rows.append(
            f'<tr id="n{x["n"]}"><td>{x["n"]}</td><td class="h" lang="{lang}">{num}</td>'
            f'<td class="h" lang="{lang}">{x["word"]}</td>'
            f'<td class="rom">{x["roman"]}{also}</td></tr>'
        )
    return ('<table class="ex numtab"><thead><tr><th>Number</th>'
            f'<th>{script} digit</th>'
            f'<th>{d["languageName"]} word</th><th>Say it</th></tr></thead><tbody>'
            + "".join(rows) + "</tbody></table>")


def update_page(spec: dict, check: bool) -> str | None:
    """Return an error string when the table is stale, else None."""
    d = load(spec)
    path = ROOT / spec["slug"] / "index.html"
    if not path.exists():
        return f"MISSING {spec['slug']}/index.html"
    html = path.read_text(encoding="utf-8")
    if TABLE_START not in html or TABLE_END not in html:
        return f"{spec['slug']}/index.html has no numbers-table markers"
    a = html.index(TABLE_START) + len(TABLE_START)
    b = html.index(TABLE_END)
    want = "\n" + table(spec, d) + "\n"
    if html[a:b] != want:
        if check:
            return f"STALE table in {spec['slug']}/index.html — run: python3 tools/build-numbers-pages.py"
        path.write_text(html[:a] + want + html[b:], encoding="utf-8")
    return None


def main() -> int:
    check = "--check" in sys.argv
    problems = []

    js = render_js()
    js_path = ROOT / "js/numbers-data.js"
    if check:
        if not js_path.exists() or js_path.read_text(encoding="utf-8") != js:
            problems.append("STALE js/numbers-data.js — run: python3 tools/build-numbers-pages.py")
    else:
        js_path.write_text(js, encoding="utf-8")

    for spec in PAGES:
        err = update_page(spec, check)
        if err:
            problems.append(err)

    if check:
        if problems:
            print("\n".join(problems))
            return 1
        print("ok    numbers data and tables are current")
        return 0
    print(f"wrote js/numbers-data.js and {len(PAGES)} table(s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

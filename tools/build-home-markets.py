#!/usr/bin/env python3
"""Regenerate the static country grid in the home page's markets section.

Usability 6 / 12 / 14 (3 Oct 2026)
----------------------------------
The home page's "Students from around the world" section shipped no
server-rendered grid at all: js/country-marquee.js built two continuous
marquees of button-chips at runtime, so

  · a crawler and a reader without JavaScript saw one line inside <noscript>
    ("See the country research index") and nothing else — Googlebot/human
    parity broken (repo rule R-1),
  · the interactive rails were a wall of ~100 chips in no order, with no
    grouping and no followable links (issue 6),
  · the only real link in the section was an orphan button under the wall
    (issue 14), with no heading and no sentence saying where it goes.

This tool writes the static half: the same 52 countries the runtime data
describes (js/country-languages.js ← data/global/language-country-relations
.json, quality-gated), grouped by region, each one a real link to its
country page when that page exists. js/country-marquee.js then appends the
interactive panel behind a labelled <details> — enhancement, never
replacement.

Only the block between the markers is generated:

    <!-- ekguru:home-markets:start (generated by tools/build-home-markets.py) -->
    <!-- ekguru:home-markets:end -->

Run:  python3 tools/build-home-markets.py [--check]
      --check exits 1 if index.html is out of date (CI/gate use)
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)

FILE = "index.html"
START = "<!-- ekguru:home-markets:start (generated by tools/build-home-markets.py) -->"
END = "<!-- ekguru:home-markets:end -->"

# The countries the runtime data describes, grouped the way a reader thinks
# about them. Every country in the data appears exactly once.
REGIONS = [
    ("South Asia", ["AF", "BD", "BT", "IN", "MV", "NP", "PK", "LK"]),
    ("Asia–Pacific", ["BN", "KH", "ID", "LA", "MY", "MM", "NZ", "PH", "SG", "TH", "TL", "VN"]),
    ("Middle East & Gulf", ["BH", "IR", "IQ", "IL", "JO", "KW", "LB", "OM", "QA", "SA", "SY", "TR", "AE", "YE"]),
    ("Central Asia & Caucasus", ["AM", "AZ", "GE", "KZ", "KG", "TJ", "TM", "UZ"]),
    ("Europe", ["MD", "PL", "RO", "GB"]),
    ("Americas", ["CA", "HT", "PE", "US"]),
    ("Africa", ["ET", "ZA"]),
]

# Names that do not slugify into their directory name.
SLUG_OVERRIDE = {
    "United States": "usa",
    "United Kingdom": "uk",
    "United Arab Emirates": "uae",
    "Türkiye": "turkiye",
    "Timor-Leste": "timor-leste",
}


def esc(s):
    return (str(s).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
            .replace('"', "&quot;"))


def country_slug(name):
    if name in SLUG_OVERRIDE:
        return SLUG_OVERRIDE[name]
    slug = re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")
    return slug


def country_href(name, slug):
    """The country's own page when it exists, the research index otherwise."""
    if os.path.isdir("learn-hindi-from-%s" % slug):
        return "learn-hindi-from-%s/" % slug, True
    return "learn-hindi-by-country/", False


def load_data():
    raw = open("js/country-languages.js", encoding="utf-8").read()
    m = re.search(r"window\.EKGURU_COUNTRY_LANGS = (\[[\s\S]*?\]);", raw)
    if not m:
        raise SystemExit("js/country-languages.js: cannot find EKGURU_COUNTRY_LANGS")
    return json.loads(m.group(1))


def block(data):
    by_cc = {d["cc"]: d for d in data}
    placed = set()
    out = [START]

    # The four country pages that are worth naming first: the ones the
    # relation data actually holds the most evidence for.
    ranked = sorted(data, key=lambda d: (-sum(1 for l in d["langs"] if l.get("quality") == "VERIFIED"), d["name"]))[:4]
    out.append('<p class="eg-cc-hint">Source-gated language relationships, checked against published '
               'records. Pages with the strongest evidence: <b>%s</b>.</p>'
               % " · ".join('<a href="%s">%s</a>' % (country_href(c["name"], country_slug(c["name"]))[0], esc(c["name"]))
                            for c in ranked))

    for region, ccs in REGIONS:
        items = []
        for cc in ccs:
            c = by_cc.get(cc)
            if not c or cc in placed:
                continue
            placed.add(cc)
            href, real = country_href(c["name"], country_slug(c["name"]))
            verified = sum(1 for l in c["langs"] if l.get("quality") == "VERIFIED")
            note = "%d verified %s" % (verified, "language" if verified == 1 else "languages")
            label = c["name"] + (" " if real else " (index) ")
            items.append('<li><a href="%s">%s<small>%s</small></a></li>' % (href, esc(label), note))
        if not items:
            continue
        out.append('  <section class="mkt-region-block">')
        out.append('    <h3 class="mkt-region">%s</h3>' % esc(region))
        out.append('    <ul class="mkt-grid">')
        out.extend("      " + i for i in items)
        out.append("    </ul>")
        out.append("  </section>")

    missing = [d["cc"] for d in data if d["cc"] not in placed]
    if missing:
        raise SystemExit("region table does not cover: %s" % ", ".join(missing))

    out.append(END)
    return "\n".join(out)


def main():
    check = "--check" in sys.argv
    data = load_data()
    html = open(FILE, encoding="utf-8").read()

    if START in html and END in html:
        updated = re.sub(re.escape(START) + r"[\s\S]*?" + re.escape(END), lambda m: block(data), html)
    else:
        # first run: put the grid inside #markets, ahead of the noscript fallback
        anchor = re.search(r'(<div class="markets reveal" id="markets"[^>]*>)', html)
        if not anchor:
            raise SystemExit(FILE + ": cannot find the #markets host to insert the grid into")
        updated = html[:anchor.end()] + "\n" + block(data) + html[anchor.end():]

    if updated == html:
        print("ok    %s already up to date (%d countries)" % (FILE, len(data)))
        return 0
    if check:
        print("STALE %s — run tools/build-home-markets.py" % FILE)
        return 1
    open(FILE, "w", encoding="utf-8").write(updated)
    print("wrote %s (markets grid, %d countries)" % (FILE, len(data)))
    return 0


if __name__ == "__main__":
    sys.exit(main())

#!/usr/bin/env python3
"""Script-aware, AA-tested per-language tokens. Patterns are original geometry, not cultural claims.

Themes exist for every language that has a catalogue course or a starter pack. They style only the
additive v2 components (accent, script font stack, line height); they never alter indexing.
"""

#!/usr/bin/env node
/* ==========================================================================
   EkGuru — HOME PAGE TUTOR CARDS
   --------------------------------------------------------------------------
   Rewrites the static tutor list on the English home page from the live
   roster (js/tutors/*.js + the sheet overrides, through tools/lib/site-data.js)
   and keeps the tutor-profile figure in the hero in step with it.

   WHY THIS TOOL EXISTS
   --------------------
   The cards in index.html were hand-written, and they had drifted from the
   tutors they describe:

     · every one of them quoted $6 — Hemlata's rate is $12, Tara's $8
     · Hemlata and Tara showed "★★★★★ 5.0" with zero reviews between them
     · adding a tutor meant copying a 20-line block of markup by hand,
       which is how a new tutor ends up on find-tutors.html and nowhere
       else — the same failure js/tutors/_registry.js warns about

   js/main.js replaces this grid with live cards once JavaScript runs, so a
   browser visitor never saw the stale numbers — but a crawler, a reader
   with JavaScript off, and Google's cached copy all did. The static page
   has to be as true as the live one.

   Only the block between the markers is generated:

     <!-- ekguru:home-tutors:start (generated by tools/build-home-tutors.js) -->
     <!-- ekguru:home-tutors:end -->

   Everything else on the page — the section heading, the i18n keys, the
   buttons under the grid — is hand-written and untouched.

   Run:  node tools/build-home-tutors.js [--check]
         --check exits 1 if index.html is out of date (CI/gate use)
   ========================================================================== */

"use strict";

const fs = require("fs");
const path = require("path");

const { loadSite } = require("./lib/site-data");

const ROOT = path.resolve(__dirname, "..");
process.chdir(ROOT);

const FILE = "index.html";
const START = "<!-- ekguru:home-tutors:start (generated by tools/build-home-tutors.js) -->";
const END = "<!-- ekguru:home-tutors:end -->";
/* Usability 9 (3 Oct 2026) — the button above the grid lives in its own
   marker pair so the generator owns it too. */
const CTA_START = "<!-- ekguru:home-tutors-cta:start (generated by tools/build-home-tutors.js) -->";
const CTA_END = "<!-- ekguru:home-tutors-cta:end -->";
const reEsc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

const esc = (s) =>
  String(s == null ? "" : s)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");

function truncate(s, n) {
  s = String(s || "").trim().replace(/\s+/g, " ");
  if (s.length <= n) return s;
  return s.slice(0, n - 1).replace(/[,;.\s]+\S*$/, "") + "…";
}

const exists = (p) => p && !/^https?:/i.test(p) && fs.existsSync(p);

/* The card-sized portrait. The build ships three sizes of every tutor photo
   (176 / 264 / full); a tutor who has only ever supplied one file falls back
   to it rather than 404ing on a size that was never generated. */
function cardPhoto(t) {
  const src = t.thumb || t.photo || "images/placeholder-tutor.jpg";
  if (/^https?:/i.test(src)) return { img: src, webp: "", base: "" };

  const base = src.replace(/\.(jpe?g|png|webp)$/i, "");
  const bigJpg = base + "-264.jpg";
  const smallJpg = base + "-176.jpg";
  const bigWebp = base + "-264.webp";
  const smallWebp = base + "-176.webp";

  const jpg = exists(bigJpg) ? bigJpg : exists(smallJpg) ? smallJpg : src;
  const webp = exists(bigWebp) && exists(smallWebp) ? [smallWebp, bigWebp] : [];
  return { img: jpg, webp, base };
}

function photoMarkup(t) {
  const p = cardPhoto(t);
  const alt = esc(t.name + ", " + (t.subject || "Hindi") + " tutor");
  if (!p.webp.length) {
    return `<img src="${esc(p.img)}" alt="${alt}" width="88" height="88" loading="lazy" decoding="async">`;
  }
  return (
    `<picture><source type="image/webp" srcset="${esc(p.webp[0])} 176w, ${esc(p.webp[1])} 264w" sizes="88px">` +
    `<img src="${esc(p.img)}" alt="${alt}" width="88" height="88" loading="lazy" decoding="async"></picture>`
  );
}

/* One line of true facts. A tutor with no reviews gets no stars — the old
   cards printed five of them from an empty reviews array.

   27 Sep 2026 master audit — the "Source profile: x.x" and "Source
   profile lists N lessons" wording is gone. Those numbers came from an
   external marketplace's listing, and the phrase attributed them to it.
   After the source gate (js/reviews.js, js/sheet.js, tools/sheetsync.js)
   reviewsCount can only ever count reviews that EkGuru students left on
   EkGuru, and EkGuru has no lesson ledger, so the lessons line is
   dropped entirely rather than relabelled. */
function metaLine(t) {
  const bits = [];
  if (t.reviewsCount) {
    const stars = "★".repeat(Math.max(1, Math.min(5, Math.round(Number(t.rating) || 0))));
    bits.push(
      `<span class="stars">${stars} <b>${Number(t.rating || 0).toFixed(1)}</b></span>` +
        `<span>${t.reviewsCount} on-site review${t.reviewsCount === 1 ? "" : "s"}</span>`
    );
  } else {
    bits.push("<span>No public reviews listed</span>");
  }
  if (t.experienceYears) {
    bits.push(`<span>Tutor states ${t.experienceYears}+ year${t.experienceYears === 1 ? "" : "s"}' experience</span>`);
  }
  return bits.join("");
}

function roleLine(t) {
  return (t.subject || "Hindi") + " tutor profile";
}

function card(t) {
  const intro = truncate(t.intro || (t.about && t.about[0]) || t.headline || "", 165);
  const price = `<b data-usd="${t.priceUSD}" data-usd-mode="bare">$${t.priceUSD}</b>`;
  return `        <article class="tcard">
          <a class="tcard-link" href="tutor/${esc(t.id)}/">${esc(t.name)} — View profile</a>
          <div class="tcard-top">
            <div class="tcard-photo">${photoMarkup(t)}</div>
            <div><h3>${esc(t.name)}</h3><p class="role">${roleLine(t)}</p>
            <div class="meta">${metaLine(t)}</div></div>
          </div>
          <div class="tcard-body"><p><strong>Tutor-provided profile:</strong> ${esc(intro)}</p></div>
          <div class="tcard-foot"><div class="price">${price}<span>Profile-listed ${esc(t.lessonLength || "50 min")} lesson · confirm current price</span></div>
          <span class="btn btn-primary btn-sm tcard-cta">View profile →</span></div>
        </article>`;
}

function block(roster, site) {
  if (!roster.length) {
    /* U0 (30 Sep 2026) — zero public tutors is a real state (the sheet
       marks every row active=no). The grid slot carries the honest
       empty state instead of an error or a blank run of cards. */
    const { emptyTutorsBlock } = require("./lib/zero-state");
    return START + "\n        " + emptyTutorsBlock({
      prefix: "", lang: "en", i18n: site.i18n,
      tag: "div",
      attrs: 'class="t-empty empty" data-eg-empty="1"'
    }) + "\n        " + END;
  }
  return START + "\n" + roster.map(card).join("\n") + "\n        " + END;
}

/* Usability 9 (3 Oct 2026) — the button above the grid said "See all tutors
   + filters" even when the grid below it said no tutor is available for
   booking, so the section contradicted itself in one screen. The generator
   writes whichever door the roster actually opens; js/main.js
   tutorsCtaHTML() keeps the same promise when it repaints live. */
function ctaBlock(roster) {
  const href = roster.length ? "find-tutors.html" : "courses/";
  const cls = roster.length ? "btn btn-primary" : "btn btn-ghost";
  const label = roster.length ? "See all tutors + filters" : "Browse the free courses →";
  return (
    CTA_START +
    "\n<p class=\"center xp-mid-cta\" data-eg-tutors-cta=\"1\" style=\"margin:0 0 22px\">\n" +
    `<a class="${cls}" data-navlink="${href}" href="${href}">${label}</a>\n</p>\n` +
    CTA_END
  );
}

/* The hero card (id="hero-tutor") is the static fallback js/main.js swaps
   for the live first tutor — a crawler and a no-JS reader see exactly what
   is written here. It is a tutor card like any other, so it obeys the same
   U0 rule: hidden tutors out, and with nobody public the card becomes the
   honest empty state (never a stale face from the registry). */
function heroBlock(roster, site) {
  const first = roster[0];
  const i18n = site.i18n || {};
  const en = (k, fb) => ((i18n.en && i18n.en[k]) || fb);
  if (!first) {
    /* U0 (30 Sep 2026) + Usability 7 & 22 (3 Oct 2026, severity Critical):
       the biggest graphic on the landing page used to open with "no tutors
       are available", so the first thing a visitor read was an absence. The
       state is still stated — it just leads with what IS open now.
       js/main.js renderHome() writes the same order on repaint. */
    return `<div class="hero-card xp-sheen" id="hero-tutor" data-eg-empty="1">
<!-- Static fallback: js/main.js replaces this card with the live first
             tutor when there is one. With no public tutors it stays the
             honest empty state (U0), leading with the free resources. -->
<p class="hc-name">${esc(en("tutors.emptyBody", "Free lessons, practice and courses are always open."))}</p>
<p class="sm">${esc(en("tutors.emptyTitle", "No tutors are available for booking right now."))}</p>
<a class="btn btn-primary btn-sm btn-block" href="learn/hindi/">${esc(en("tutors.emptyCta", "Start the free course"))}</a>
</div>`;
  }
  const photo = first.thumb || first.photo || "images/placeholder-tutor.jpg";
  return `<div class="hero-card xp-sheen" id="hero-tutor">
<!-- Static fallback: a crawler, and anyone before JavaScript runs,
             sees a real tutor here rather than a grey placeholder.
             main.js replaces this with the live first tutor. -->
<a aria-label="View ${esc(first.name)}'s profile" class="hc-link" href="tutor/${esc(first.id)}/"></a>
<img alt="${esc(first.name)}, online Hindi tutor" height="96" loading="eager" src="${esc(photo)}" width="96"/>
<p class="hc-name">${esc(first.name)}</p>
<p class="sm">Hindi tutor · ${esc(first.country || first.city || "India")}</p>
<p class="sm" style="margin:6px 0 10px">Tutor-stated profile · rating appears after the first on-site review</p>
<a class="btn btn-primary btn-sm btn-block" href="tutor/${esc(first.id)}/">View profile</a>
</div>`;
}

function main() {
  const check = process.argv.includes("--check");
  const site = loadSite();
  /* U0 — PUBLIC roster only: registry ∩ sheet active=yes. */
  const roster = site.publicTutors;

  const html = fs.readFileSync(FILE, "utf8");
  if (html.indexOf(START) === -1 || html.indexOf(END) === -1) {
    throw new Error(FILE + " is missing the home-tutors marker pair");
  }

  let updated = html.replace(
    new RegExp(reEsc(START) + "[\\s\\S]*?" + reEsc(END)),
    () => block(roster, site)
  );

  /* The button above the grid (Usability 9): same roster, same promise. */
  if (html.indexOf(CTA_START) === -1 || html.indexOf(CTA_END) === -1) {
    throw new Error(FILE + " is missing the home-tutors-cta marker pair");
  }
  updated = updated.replace(
    new RegExp(reEsc(CTA_START) + "[\\s\\S]*?" + reEsc(CTA_END)),
    () => ctaBlock(roster)
  );

  /* The hero card is a tutor card too (U0): same public roster, same
     empty-state rule. The opener matches any attribute set (the empty-state
     variant carries data-eg-empty="1" next to the id). */
  if (/<div class="hero-card xp-sheen" id="hero-tutor"[^>]*>[\s\S]*?<\/div>/.test(updated)) {
    updated = updated.replace(
      /<div class="hero-card xp-sheen" id="hero-tutor"[^>]*>[\s\S]*?<\/div>/,
      () => heroBlock(roster, site)
    );
  }

  /* The hero figure. js/main.js overwrites it with the live count on load;
     the number in the HTML is what a crawler and a no-JS visitor read. */
  updated = updated.replace(
    /(<b id="stat-tutors">)\d+(<\/b>)/,
    (m, a, b) => a + roster.length + b
  );

  if (updated === html) {
    console.log("ok    " + FILE + " already up to date (" + roster.length + " public tutors)");
    return 0;
  }
  if (check) {
    console.log("STALE " + FILE + " — run tools/build-home-tutors.js");
    return 1;
  }
  fs.writeFileSync(FILE, updated);
  console.log(
    "wrote " + FILE + " (" + html.length + " → " + updated.length + " bytes, " + roster.length + " public tutors)"
  );
  if (site.hidden.length) {
    console.log(
      "note  the sheet hides (active=no): " + site.hidden.join(", ") +
        " — they are out of every public list (U0), their profile pages are noindex," +
        " and they return the moment a row says active=yes."
    );
  }
  return 0;
}

process.exit(main());

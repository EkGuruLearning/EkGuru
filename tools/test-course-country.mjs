#!/usr/bin/env node
import fs from "node:fs";
let pass=0,fail=0; const check=(n,c,d="")=>{console.log((c?"ok    ":"FAIL  ")+n+(c?"":" — "+d));c?pass++:fail++;};
const courses=JSON.parse(fs.readFileSync("data/courses/index.json","utf8")).courses;
const relations=JSON.parse(fs.readFileSync("data/global/language-country-relations.json","utf8")).relations;
const pub=new Set(courses.filter(c=>Object.keys(c.levels||{}).length).map(c=>c.code));
const alias={arb:"ar",cmn:"zh",fil:"fil",npi:"npi",uzn:"uzn",zsm:"zsm"};
const qualified=relations.filter(r=>{const code=r.iso_639_1||alias[r.iso_639_3]||r.iso_639_3;return pub.has(code)&&r.confidence==="high"&&!r.needs_human_review&&(r.sources||[]).some(s=>s.source_url&&s.evidence_type!=="agent-compiled"&&["A","B"].includes(String(s.priority||"").split("-")[0]));});
const countries=new Set(qualified.map(r=>r.country_id));
const html=fs.readFileSync("courses/by-country/index.html","utf8");
const player=fs.readFileSync("js/course-player.js","utf8");
check("18 published courses derive from non-empty level maps",pub.size===18,String(pub.size));
check("public relations all point to published courses",qualified.every(r=>pub.has(r.iso_639_1||alias[r.iso_639_3]||r.iso_639_3)));
check("evidence-qualified set covers 20 country contexts",countries.size===20,String(countries.size));
check("static page has one card per qualified country",(html.match(/class="country-card"/g)||[]).length===countries.size);
check("static page omits the research queue",!/Documented, no course yet|id="queue"/.test(html));
check("static page names the publication total",/18 published courses/.test(html));
check("static page self-canonicalises",/href="https:\/\/ekguru\.shop\/courses\/by-country\/"\s+rel="canonical"|rel="canonical"\s+href="https:\/\/ekguru\.shop\/courses\/by-country\/"/.test(html));
check("runtime filters relations to published course codes",/publishedCodes/.test(player)&&/verifiedRelation\(row\)/.test(player));
check("runtime does not render research-only country group",!/Documented, no course yet/.test(player));
console.log(`\n${fail?"FAIL":"PASS"}  ${pass} passed, ${fail} failed\n`);process.exit(fail?1:0);

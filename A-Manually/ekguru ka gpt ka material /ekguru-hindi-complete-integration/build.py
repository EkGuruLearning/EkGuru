#!/usr/bin/env python3
"""Rebuild the six book outputs from their authored sources, then build shared study tools.
Existing site artwork/styles/scripts are seed assets; not regenerated by this command.
Use on a private extracted package, never the production repository root.
"""
from pathlib import Path
import subprocess,sys,tempfile,shutil
R=Path(__file__).resolve().parent; S=R/'site'
with tempfile.TemporaryDirectory() as t:
 work=Path(t); combined=work/'combined';combined.mkdir()
 for name in ('css','js','images'):shutil.copytree(R/'assets'/name,combined/name)
 for b in sorted((R/'source/books').iterdir()):
  if not b.is_dir():continue
  temp=work/b.name;shutil.copytree(b/'source',temp/'source',ignore=shutil.ignore_patterns('__pycache__')); (temp/'site'/'data'/'learning').mkdir(parents=True); shutil.copytree(R/'assets'/'images',temp/'site'/'images')
  subprocess.run([sys.executable,str(temp/'source/build.py')],check=True)
  for f in (temp/'site').rglob('*'):
   if not f.is_file():continue
   dest=combined/f.relative_to(temp/'site');dest.parent.mkdir(parents=True,exist_ok=True)
   if dest.exists() and dest.read_bytes()!=f.read_bytes():raise RuntimeError('Build output collision: '+str(dest))
   shutil.copy2(f,dest)
 # Stage before replacement. Only package-owned site is touched.
 subprocess.run([sys.executable,str(R/'source/build_studio.py'),str(combined)],check=True)
 if S.exists():shutil.rmtree(S)
 shutil.copytree(combined,S)
print('Combined site rebuilt.')
